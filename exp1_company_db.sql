CREATE TABLE DEPARTMENT (
    DEPT_NO            INT PRIMARY KEY,
    DEPT_NAME          VARCHAR2(20) UNIQUE NOT NULL,
    MANAGER_AADHAAR    CHAR(12),
    MANAGER_START_DATE DATE
);

CREATE TABLE EMPLOYEE (
    AADHAAR_NO         CHAR(12) PRIMARY KEY,
    NAME               VARCHAR2(15) NOT NULL,
    ADDRESS            VARCHAR2(20),
    SALARY             DECIMAL(10, 2),
    SEX                CHAR(1),
    BIRTH_DATE         DATE,
    DEPT_NO            INT NOT NULL,
    SUPERVISOR_AADHAAR CHAR(12),
    FOREIGN KEY (DEPT_NO) REFERENCES DEPARTMENT(DEPT_NO) ON DELETE CASCADE,
    FOREIGN KEY (SUPERVISOR_AADHAAR) REFERENCES EMPLOYEE(AADHAAR_NO) ON DELETE CASCADE
);

-- manager FK is added after EMPLOYEE exists (circular reference)
ALTER TABLE DEPARTMENT ADD CONSTRAINT FK_MANAGER
    FOREIGN KEY (MANAGER_AADHAAR) REFERENCES EMPLOYEE(AADHAAR_NO);

CREATE TABLE PROJECT (
    PROJECT_NO   INT PRIMARY KEY,
    PROJECT_NAME VARCHAR2(20) UNIQUE NOT NULL,
    LOCATION     VARCHAR2(15),
    DEPT_NO      INT NOT NULL,
    FOREIGN KEY (DEPT_NO) REFERENCES DEPARTMENT(DEPT_NO) ON DELETE CASCADE
);

CREATE TABLE DEPT_LOCATION (
    DEPT_NO  INT,
    LOCATION VARCHAR2(15),
    PRIMARY KEY (DEPT_NO, LOCATION),
    FOREIGN KEY (DEPT_NO) REFERENCES DEPARTMENT(DEPT_NO) ON DELETE CASCADE
);

CREATE TABLE WORKS_ON (
    AADHAAR_NO     CHAR(12),
    PROJECT_NO     INT,
    HOURS_PER_WEEK DECIMAL(4, 1) NOT NULL,
    PRIMARY KEY (AADHAAR_NO, PROJECT_NO),
    FOREIGN KEY (AADHAAR_NO) REFERENCES EMPLOYEE(AADHAAR_NO) ON DELETE CASCADE,
    FOREIGN KEY (PROJECT_NO) REFERENCES PROJECT(PROJECT_NO) ON DELETE CASCADE
);

CREATE TABLE DEPENDENT (
    AADHAAR_NO     CHAR(12),
    DEPENDENT_NAME VARCHAR2(15),
    SEX            CHAR(1),
    BIRTH_DATE     DATE,
    RELATIONSHIP   VARCHAR2(15),
    PRIMARY KEY (AADHAAR_NO, DEPENDENT_NAME),
    FOREIGN KEY (AADHAAR_NO) REFERENCES EMPLOYEE(AADHAAR_NO) ON DELETE CASCADE
);

