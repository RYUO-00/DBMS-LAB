-- STEP 0 : drop old tables (ignored if they do not exist)
DECLARE
    TYPE name_list IS TABLE OF VARCHAR2(30);
    tables name_list := name_list(
        'IAMARKS',
        'CLASS_ALLOCATION',
        'COURSE',
        'SEMSEC',
        'STUDENT'
    );
BEGIN
    FOR i IN 1 .. tables.COUNT LOOP
        BEGIN
            EXECUTE IMMEDIATE 'DROP TABLE ' || tables(i) || ' CASCADE CONSTRAINTS';
        EXCEPTION
            WHEN OTHERS THEN
                -- ORA-00942 = table does not exist -> ignore it
                IF SQLCODE != -942 THEN
                    RAISE;
                END IF;
        END;
    END LOOP;
END;
/

-- =====================================================================
-- EXPERIMENT 3 : COLLEGE DATABASE
-- =====================================================================

CREATE TABLE STUDENT (
    USN    VARCHAR2(15) PRIMARY KEY,
    SNAME  VARCHAR2(10) NOT NULL,
    PHONE  VARCHAR2(15),
    GENDER VARCHAR2(10)
);

CREATE TABLE SEMSEC (
    SSID     INT PRIMARY KEY,
    SEMESTER INT NOT NULL,
    SECTION  CHAR(1) NOT NULL
);

CREATE TABLE COURSE (
    SUBCODE  VARCHAR2(10) PRIMARY KEY,
    TITLE    VARCHAR2(40) NOT NULL,
    SEMESTER INT NOT NULL,
    CREDITS  INT NOT NULL
);

CREATE TABLE CLASS_ALLOCATION (
    USN  VARCHAR2(15),
    SSID INT,
    PRIMARY KEY (USN, SSID),
    FOREIGN KEY (USN)  REFERENCES STUDENT(USN),
    FOREIGN KEY (SSID) REFERENCES SEMSEC(SSID)
);

CREATE TABLE IAMARKS (
    USN     VARCHAR2(15),
    SUBCODE VARCHAR2(10),
    SSID    INT,
    TEST1   DECIMAL(5,2),
    TEST2   DECIMAL(5,2),
    TEST3   DECIMAL(5,2),
    FINALIA DECIMAL(5,2),
    PRIMARY KEY (USN, SUBCODE, SSID),
    FOREIGN KEY (USN, SSID) REFERENCES CLASS_ALLOCATION(USN, SSID),
    FOREIGN KEY (SUBCODE)   REFERENCES COURSE(SUBCODE)
);

