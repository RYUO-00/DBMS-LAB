-- STEP 0 : drop old tables (ignored if they do not exist)
DECLARE
    TYPE name_list IS TABLE OF VARCHAR2(30);
    tables name_list := name_list(
        'LOAN',
        'DEPOSITOR',
        'ACCOUNT',
        'CUSTOMER',
        'BRANCH'
    );
BEGIN
    FOR i IN 1 .. tables.COUNT LOOP
        BEGIN
            EXECUTE IMMEDIATE 'DROP TABLE ' || tables(i) || ' CASCADE CONSTRAINTS';
        EXCEPTION
            WHEN OTHERS THEN
                -- ORA-00942 = table does not exist -> ignore it
                IF SQLCODE != -942 THEN
                    RAISE;
                END IF;
        END;
    END LOOP;
END;
/

-- =====================================================================
-- EXPERIMENT 4 : BANK DATABASE
-- =====================================================================

CREATE TABLE BRANCH (
    BRANCH_ID   INT PRIMARY KEY,
    BRANCH_NAME VARCHAR2(25) NOT NULL,
    CITY        VARCHAR2(15) NOT NULL,
    ASSETS      DECIMAL(15,2) NOT NULL
);

CREATE TABLE CUSTOMER (
    CUSTOMER_ID   INT PRIMARY KEY,
    CUSTOMER_NAME VARCHAR2(20) NOT NULL,
    STREET        VARCHAR2(25),
    CITY          VARCHAR2(15)
);

CREATE TABLE ACCOUNT (
    ACCOUNT_NO   INT PRIMARY KEY,
    ACCOUNT_TYPE VARCHAR2(15) NOT NULL,
    BALANCE      DECIMAL(12,2) NOT NULL,
    BRANCH_ID    INT NOT NULL,
    FOREIGN KEY (BRANCH_ID) REFERENCES BRANCH(BRANCH_ID)
);

CREATE TABLE DEPOSITOR (
    CUSTOMER_ID INT,
    ACCOUNT_NO  INT,
    PRIMARY KEY (CUSTOMER_ID, ACCOUNT_NO),
    FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMER(CUSTOMER_ID),
    FOREIGN KEY (ACCOUNT_NO)  REFERENCES ACCOUNT(ACCOUNT_NO)
);

CREATE TABLE LOAN (
    LOAN_NO     INT PRIMARY KEY,
    BRANCH_ID   INT NOT NULL,
    AMOUNT      DECIMAL(12,2) NOT NULL,
    CUSTOMER_ID INT NOT NULL,
    FOREIGN KEY (BRANCH_ID)   REFERENCES BRANCH(BRANCH_ID),
    FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMER(CUSTOMER_ID)
);

