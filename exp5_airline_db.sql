-- EXPERIMENT 5 : AIRLINE DATABASE  (Oracle SQL*Plus script)
-- Run with:  @exp5_airline_db.sql
-- Drops this experiment's tables if they exist, then recreates them
-- and inserts all the data (safe to run repeatedly).
-- =====================================================================

SET DEFINE OFF
SET ECHO OFF
SET FEEDBACK ON

-- STEP 0 : drop old tables (ignored if they do not exist)
DECLARE
    TYPE name_list IS TABLE OF VARCHAR2(30);
    tables name_list := name_list(
        'CERTIFICATION',
        'FLIGHT',
        'AIRLINE_EMPLOYEE',
        'AIRCRAFT'
    );
BEGIN
    FOR i IN 1 .. tables.COUNT LOOP
        BEGIN
            EXECUTE IMMEDIATE 'DROP TABLE ' || tables(i) || ' CASCADE CONSTRAINTS';
        EXCEPTION
            WHEN OTHERS THEN
                -- ORA-00942 = table does not exist -> ignore it
                IF SQLCODE != -942 THEN
                    RAISE;
                END IF;
        END;
    END LOOP;
END;
/

-- =====================================================================
-- EXPERIMENT 5 : AIRLINE DATABASE
-- (EMPLOYEE is named AIRLINE_EMPLOYEE here so it does not clash with
--  the EMPLOYEE table of Experiment 1)
-- DEPARTURE_TIME / ARRIVAL_TIME are stored as 'HH24:MI:SS' text because
-- Oracle has no plain TIME datatype.
-- =====================================================================

CREATE TABLE AIRCRAFT (
    AIRCRAFT_ID    INT PRIMARY KEY,
    AIRCRAFT_NAME  VARCHAR2(15) NOT NULL,
    CRUISING_RANGE INT NOT NULL
);

CREATE TABLE AIRLINE_EMPLOYEE (
    EMPLOYEE_ID   INT PRIMARY KEY,
    EMPLOYEE_NAME VARCHAR2(20) NOT NULL,
    SALARY        DECIMAL(10,2) NOT NULL
);

CREATE TABLE FLIGHT (
    FLIGHT_NO      VARCHAR2(10) PRIMARY KEY,
    SOURCE         VARCHAR2(15) NOT NULL,
    DESTINATION    VARCHAR2(15) NOT NULL,
    DISTANCE       INT NOT NULL,
    DEPARTURE_TIME VARCHAR2(8) NOT NULL,
    ARRIVAL_TIME   VARCHAR2(8) NOT NULL,
    COST           DECIMAL(10,2) NOT NULL
);

CREATE TABLE CERTIFICATION (
    EMPLOYEE_ID INT,
    AIRCRAFT_ID INT,
    PRIMARY KEY (EMPLOYEE_ID, AIRCRAFT_ID),
    FOREIGN KEY (EMPLOYEE_ID) REFERENCES AIRLINE_EMPLOYEE(EMPLOYEE_ID),
    FOREIGN KEY (AIRCRAFT_ID) REFERENCES AIRCRAFT(AIRCRAFT_ID)
);

