CREATE TABLE PROGRAM (
    PROGRAM_ID   INT PRIMARY KEY,
    PROGRAM_NAME VARCHAR2(30) NOT NULL,
    ADDRESS      VARCHAR2(25) NOT NULL
);

CREATE TABLE PUBLISHER (
    PUBLISHER_ID   INT PRIMARY KEY,
    PUBLISHER_NAME VARCHAR2(30) NOT NULL,
    ADDRESS        VARCHAR2(20) NOT NULL,
    PHONE          VARCHAR2(15) NOT NULL
);

CREATE TABLE BOOK (
    BOOK_ID          INT PRIMARY KEY,
    TITLE            VARCHAR2(40) NOT NULL,
    PUBLISHER_ID     INT NOT NULL,
    PUBLICATION_YEAR INT,
    CONSTRAINT FK_BOOK_PUBLISHER FOREIGN KEY (PUBLISHER_ID)
        REFERENCES PUBLISHER(PUBLISHER_ID) ON DELETE CASCADE
);

CREATE TABLE AUTHOR (
    AUTHOR_ID   INT PRIMARY KEY,
    AUTHOR_NAME VARCHAR2(30) NOT NULL
);

CREATE TABLE BOOK_AUTHOR (
    BOOK_ID   INT,
    AUTHOR_ID INT,
    PRIMARY KEY (BOOK_ID, AUTHOR_ID),
    CONSTRAINT FK_BA_BOOK   FOREIGN KEY (BOOK_ID)   REFERENCES BOOK(BOOK_ID)     ON DELETE CASCADE,
    CONSTRAINT FK_BA_AUTHOR FOREIGN KEY (AUTHOR_ID) REFERENCES AUTHOR(AUTHOR_ID) ON DELETE CASCADE
);

CREATE TABLE PROGRAM_BOOK (
    PROGRAM_ID       INT,
    BOOK_ID          INT,
    NUMBER_OF_COPIES INT NOT NULL,
    PRIMARY KEY (PROGRAM_ID, BOOK_ID),
    CONSTRAINT FK_PB_PROGRAM FOREIGN KEY (PROGRAM_ID) REFERENCES PROGRAM(PROGRAM_ID) ON DELETE CASCADE,
    CONSTRAINT FK_PB_BOOK    FOREIGN KEY (BOOK_ID)    REFERENCES BOOK(BOOK_ID)       ON DELETE CASCADE,
    CONSTRAINT CHK_COPIES CHECK (NUMBER_OF_COPIES >= 0)
);

CREATE TABLE LENDING (
    CARD_NO    INT PRIMARY KEY,
    PROGRAM_ID INT NOT NULL,
    BOOK_ID    INT NOT NULL,
    OUT_DATE   DATE NOT NULL,
    DUE_DATE   DATE NOT NULL,
    CONSTRAINT FK_LENDING_PROGRAM FOREIGN KEY (PROGRAM_ID) REFERENCES PROGRAM(PROGRAM_ID),
    CONSTRAINT FK_LENDING_BOOK    FOREIGN KEY (BOOK_ID)    REFERENCES BOOK(BOOK_ID),
    CONSTRAINT CHK_DATES CHECK (DUE_DATE >= OUT_DATE)
);

